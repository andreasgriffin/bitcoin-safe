from __future__ import annotations

import gzip
import ipaddress
import json
import logging
from collections import OrderedDict
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from bitcoin_safe.util import resource_path

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class GeoLocation:
    latitude: float
    longitude: float
    country_code: str | None = None


class RoughGeoIpDatabase:
    """Look up rough geo coordinates for IP addresses.

    The backing JSON file is expected to be generated by
    `tools/download_rough_geoip_db.py`.
    """

    def __init__(self, db_path: Path | None = None) -> None:
        self.db_path = db_path or Path(resource_path("data", "geoip_rough_v1.json.gz"))
        self._loaded = False
        self._ipv4_prefix = 12
        self._ipv6_prefix = 32
        self._ipv4_map: dict[int, GeoLocation] = {}
        self._ipv6_map: dict[int, GeoLocation] = {}
        self._host_cache: OrderedDict[str, GeoLocation | None] = OrderedDict()

    def _load(self) -> None:
        if self._loaded:
            return

        self._loaded = True
        try:
            stat = self.db_path.stat()
        except OSError:
            logger.info("GeoIP rough database not found at %s", self.db_path)
            return

        try:
            prefix_lengths, self._ipv4_map, self._ipv6_map = self._load_database(
                str(self.db_path.resolve()), stat.st_mtime_ns, stat.st_size
            )
        except Exception:
            logger.exception("Failed reading GeoIP rough database from %s", self.db_path)
            return

        self._ipv4_prefix, self._ipv6_prefix = prefix_lengths

    @classmethod
    @lru_cache(maxsize=8)
    def _load_database(
        cls, db_path: str, modified_ns: int, size: int
    ) -> tuple[tuple[int, int], dict[int, GeoLocation], dict[int, GeoLocation]]:
        del modified_ns, size
        path = Path(db_path)
        if path.suffix == ".gz":
            with gzip.open(path, "rt", encoding="utf-8") as file_handle:
                payload = json.load(file_handle)
        else:
            payload = json.loads(path.read_text(encoding="utf-8"))

        prefix_lengths = payload.get("prefix_lengths", {})
        ipv4_prefix = int(prefix_lengths.get("ipv4", 12))
        ipv6_prefix = int(prefix_lengths.get("ipv6", 32))
        ipv4_map = cls._decode_map(payload.get("ipv4", {}))
        ipv6_map = cls._decode_map(payload.get("ipv6", {}))
        return (ipv4_prefix, ipv6_prefix), ipv4_map, ipv6_map

    @staticmethod
    def _decode_map(data: dict[str, list[object]]) -> dict[int, GeoLocation]:
        mapped: dict[int, GeoLocation] = {}
        for key_str, value in data.items():
            if len(value) < 2:
                continue

            raw_latitude = value[0]
            raw_longitude = value[1]
            if not isinstance(raw_latitude, int | float | str):
                continue
            if not isinstance(raw_longitude, int | float | str):
                continue

            try:
                key = int(key_str)
                latitude = float(raw_latitude)
                longitude = float(raw_longitude)
            except Exception:
                continue

            country_code: str | None = None
            if len(value) >= 3 and isinstance(value[2], str):
                country_code = value[2]

            mapped[key] = GeoLocation(latitude=latitude, longitude=longitude, country_code=country_code)

        return mapped

    def lookup_ip(self, ip: ipaddress.IPv4Address | ipaddress.IPv6Address) -> GeoLocation | None:
        self._load()

        if ip.version == 4:
            prefix_key = int(ip) >> (32 - self._ipv4_prefix)
            return self._ipv4_map.get(prefix_key)

        prefix_key = int(ip) >> (128 - self._ipv6_prefix)
        return self._ipv6_map.get(prefix_key)

    def lookup_host(self, host: str) -> GeoLocation | None:
        if host in self._host_cache:
            self._host_cache.move_to_end(host)
            return self._host_cache[host]

        try:
            ip = ipaddress.ip_address(host)
        except ValueError:
            location = None
        else:
            location = self.lookup_ip(ip)

        self._host_cache[host] = location
        if len(self._host_cache) > 8192:
            self._host_cache.popitem(last=False)
        return location
